// Example GEISA waveform subscribe + frame decoder
//
// This example demonstrates how an application can:
//   1) Serialize a GeisaWaveform_Req subscribe request (protobuf)
//   2) Parse a GeisaWaveform_Rsp subscribe response (protobuf) to obtain:
//        - waveform stream metadata (sample type, channel counts, rates)
//        - the per-application AF_UNIX SOCK_SEQPACKET socket path
//   3) Read and decode one geisa_waveform_frame from a unix socket or
//      fallback frame file path and print header fields, preview samples,
//      and min/max summary.
//
// Notes:
// - This example does not implement MQTT publish/subscribe. It emits and parses
//   protobuf payloads so you can wire them into your MQTT client of choice.
// - The waveform data-plane payload is a native binary frame (from unix
//   domain SOCK_SEQPACKET socket or fallback frame file path); it is not a
//   protobuf message.
//
// Build example:
//
//   make clean
//   make cpp
//   c++ -std=c++17 -O2 \
//     -I build/cpp \
//     $(pkg-config --cflags protobuf) \
//     examples/waveform_subscribe_and_read.cpp \
//     build/cpp/waveform.pb.cc \
//     build/cpp/geisa-status.pb.cc \
//     $(pkg-config --libs protobuf) \
//     -pthread \
//     -o /tmp/waveform_subscribe_and_read
//
// Usage:
//
//   # Writes a subscribe request protobuf payload:
//   /tmp/waveform_subscribe_and_read --write-req /tmp/waveform-req.bin
//
//   # Write a sample subscribe response protobuf payload:
//   /tmp/waveform_subscribe_and_read --write-rsp-sample /tmp/waveform-rsp.bin
//
//   # Parses a subscribe response protobuf payload and reads one waveform frame:
//   /tmp/waveform_subscribe_and_read --read-rsp /tmp/waveform-rsp.bin
//
//   # Runs a full demo (write sample response/frame, then read/decode):
//   /tmp/waveform_subscribe_and_read --demo
//
//------------------------------------------------------------------------------

