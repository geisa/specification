/*
 * Matches the spec's geisa_waveform_frame header layout:
 *   int64 timestamp_ms
 *   uint32 sequence_num
 *   uint32 reserved
 * followed by samples payload
 *
 * Payload length is derived from recv() size.
 *
 * Sample interpretation depends on GeisaWaveform_SampleType and
 * total_channel_count.
 */
#pragma pack(push, 1)
struct GeisaWaveformFrameHeader {
  int64_t timestamp_ms;
  uint32_t sequence_num;
  uint32_t reserved;
};
#pragma pack(pop)

static_assert(sizeof(GeisaWaveformFrameHeader) == 16, "Unexpected header size");

int ConnectUnixSeqpacket(const std::string& path);
